const CURRENCY_MAP = new Map<string, CurrencyRecord>();
for (const curr of ISO_CURRENCIES) {
  CURRENCY_MAP.set(curr.code.toUpperCase(), curr);
}

export function getCurrency(code: string): CurrencyRecord | undefined {
  return CURRENCY_MAP.get(code.toUpperCase());
}

export function getAllCurrencies(): CurrencyRecord[] {
  return ISO_CURRENCIES;
}

export function getPopularCurrencies(): CurrencyRecord[] {
  return ISO_CURRENCIES.filter((c) => c.isPopular);
}

/**
 * High-performance indexed currency search across code, name, country, symbol, and aliases.
 */
export function searchCurrencies(query: string): CurrencyRecord[] {
  const clean = query.trim().toLowerCase();
  if (!clean) return ISO_CURRENCIES;

  return ISO_CURRENCIES.filter((curr) => {
    if (curr.code.toLowerCase().includes(clean)) return true;
    if (curr.name.toLowerCase().includes(clean)) return true;
    if (curr.countryOrRegion.toLowerCase().includes(clean)) return true;
    if (curr.symbol.toLowerCase() === clean) return true;
    if (curr.numericCode === clean) return true;
    if (curr.aliases.some((a) => a.toLowerCase().includes(clean))) return true;
    return false;
  });
}
