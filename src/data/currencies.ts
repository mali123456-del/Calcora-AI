export function findCurrency(code: string): CurrencyDefinition | undefined {
  return CURRENCIES.find(c => c.code.toUpperCase() === code.toUpperCase());
}

export function searchCurrencies(query: string): CurrencyDefinition[] {
  const q = query.trim().toLowerCase();
  if (!q) return [...CURRENCIES];
  return CURRENCIES.filter(c => [c.code,c.name,c.countryOrRegion,c.symbol,...c.aliases].some(v => v.toLowerCase().includes(q)));
}
