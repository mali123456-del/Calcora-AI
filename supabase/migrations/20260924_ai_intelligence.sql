create table if not exists public.ai_intelligence_items (
 id uuid primary key default gen_random_uuid(), source_id text not null, source_name text not null,
 kind text not null check (kind in ('model-catalog','dataset-catalog','release-feed','official-docs')),
 title text not null, url text not null, summary text not null default '', content text not null,
 tags text[] not null default '{}', license text, published_at timestamptz, content_hash text not null unique,
 relevance_score numeric(4,3) not null default 0, status text not null default 'candidate' check (status in ('candidate','verified','active','rejected')),
 created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create index if not exists ai_intelligence_items_status_idx on public.ai_intelligence_items(status, relevance_score desc);
create index if not exists ai_intelligence_items_source_idx on public.ai_intelligence_items(source_id, created_at desc);
create table if not exists public.ai_intelligence_runs (
 id bigint generated by default as identity primary key, started_at timestamptz not null, finished_at timestamptz not null,
 scanned_sources integer not null default 0, fetched_sources integer not null default 0, discovered_items integer not null default 0,
 new_items integer not null default 0, activated_items integer not null default 0, errors jsonb not null default '[]'::jsonb, created_at timestamptz not null default now()
);
alter table public.ai_intelligence_items enable row level security;
alter table public.ai_intelligence_runs enable row level security;
revoke all on table public.ai_intelligence_items from anon, authenticated;
revoke all on table public.ai_intelligence_runs from anon, authenticated;